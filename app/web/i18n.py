def t(key, **kwargs):
    """
    Looks up `key` in the current session's chosen language, falling
    back to English, then to the key itself if truly missing - a
    visible raw key in the UI is a findable bug during development,
    never a 500 error for a real user mid-upload.
    """
    lang = session.get("lang", DEFAULT_LANGUAGE)
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**kwargs) if kwargs else text
